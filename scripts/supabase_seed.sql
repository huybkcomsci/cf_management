-- Supabase bootstrap script for CafeManagement
-- Run this in Supabase SQL Editor after clearing the schema.
--
-- What this script creates:
-- - simple Users table for plain-text login
-- - product/category/customer/employee/invoice tables
-- - seed data for 3 demo users and sample business data
--
-- Login demo accounts:
-- - admin@cafemanagement.local / Admin@123
-- - keytoan@cafemanagement.local / Admin@123
-- - thunga@cafemanagement.local / Admin@123

