    "IdPhieuNhap" uuid NOT NULL REFERENCES "Phieunhap"("Id") ON DELETE CASCADE,
    "SoLuong" integer NOT NULL,
    "DonGia" numeric(10,2) NOT NULL,
    "GhiChu" varchar(200)
);

CREATE TABLE IF NOT EXISTS "Phieuchi" (
    "Id" uuid PRIMARY KEY,
    "MaPC" varchar(50) NOT NULL UNIQUE,
    "IdNV" uuid,
    "IdNCC" uuid,
    "NgayLapPC" timestamp NOT NULL,
    "SoTien" numeric(12,2) NOT NULL,
    "PhuongThucThanhToan" integer NOT NULL DEFAULT 1,
    "LoaiChiPhi" integer NOT NULL DEFAULT 0,
    "TrangThai" integer NOT NULL DEFAULT 0,
    "GhiChu" varchar(200),
    "NgayTao" timestamp NOT NULL,
    "NgayCapNhat" timestamp NOT NULL
);

CREATE TABLE IF NOT EXISTS "Dinhluong" (
    "Id" uuid PRIMARY KEY,
    "IdSP" uuid NOT NULL REFERENCES "Sanpham"("Id") ON DELETE CASCADE,
    "IdThanhPhan" uuid NOT NULL REFERENCES "Sanpham"("Id") ON DELETE CASCADE,
    "SoLuong" integer NOT NULL,
    "DonVi" varchar(50),
    "GhiChu" varchar(200),
    "NgayTao" timestamp NOT NULL,
    "NgayCapNhat" timestamp NOT NULL
);

CREATE TABLE IF NOT EXISTS "Tieuhao" (
    "Id" uuid PRIMARY KEY,
    "IdSP" uuid NOT NULL REFERENCES "Sanpham"("Id") ON DELETE RESTRICT,
    "IdHoadonCT" uuid NOT NULL REFERENCES "HoadonCT"("Id") ON DELETE CASCADE,
    "SoLuong" integer NOT NULL,
    "DonGiaVon" numeric(10,2) NOT NULL,
    "NgayTao" timestamp NOT NULL
);

CREATE TABLE IF NOT EXISTS "Chamcong" (
    "Id" uuid PRIMARY KEY,
    "IdNV" uuid NOT NULL REFERENCES "Nhanvien"("Id") ON DELETE CASCADE,
    "Ngay" timestamp NOT NULL,
    "GioVao" interval,
    "GioRa" interval,
    "TrangThai" integer NOT NULL DEFAULT 0,
    "GhiChu" varchar(200),
    "NgayTao" timestamp NOT NULL
