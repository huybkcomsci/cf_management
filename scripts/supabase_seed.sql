    "NgayTao" timestamp NOT NULL,
    "NgayCapNhat" timestamp NOT NULL
);

CREATE TABLE IF NOT EXISTS "HoadonCT" (
    "Id" uuid PRIMARY KEY,
    "IdHD" uuid NOT NULL REFERENCES "Hoadon"("Id") ON DELETE CASCADE,
    "IdSP" uuid NOT NULL REFERENCES "Sanpham"("Id") ON DELETE RESTRICT,
    "SoLuong" integer NOT NULL,
    "DonGia" numeric(10,2) NOT NULL,
    "ThanhTien" numeric(12,2) NOT NULL,
    "GhiChu" varchar(200)
);

CREATE TABLE IF NOT EXISTS "Phieunhap" (
