CREATE TABLE IF NOT EXISTS "Bangluong" (
    "Id" uuid PRIMARY KEY,
    "IdNV" uuid NOT NULL REFERENCES "Nhanvien"("Id") ON DELETE CASCADE,
    "Nam" integer NOT NULL,
    "Thang" integer NOT NULL,
    "SoGio" integer NOT NULL,
    "Luong" numeric(12,2) NOT NULL,
