CREATE EXTENSION IF NOT EXISTS pgcrypto;

-- --------------------------------------------------
-- Authentication
-- --------------------------------------------------
CREATE TABLE IF NOT EXISTS "Users" (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "Email" varchar(100) NOT NULL,
    "Password" text NOT NULL,
    "Role" varchar(50) NOT NULL,
    "IsActive" boolean NOT NULL DEFAULT true,
    "CreatedDate" timestamp with time zone NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS "IX_Users_Email" ON "Users"("Email");

-- --------------------------------------------------
-- Core business tables
-- --------------------------------------------------
CREATE TABLE IF NOT EXISTS "Product" (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "Name" varchar(200) NOT NULL,
    "Description" varchar(500),
    "Price" numeric(10,2) NOT NULL
);

CREATE TABLE IF NOT EXISTS "NhomSP" (
    "Id" uuid PRIMARY KEY,
    "TenNhom" varchar(100) NOT NULL,
    "MoTa" varchar(500),
    "PhanLoai" integer NOT NULL,
    "NgayTao" timestamp NOT NULL,
    "NgayCapNhat" timestamp NOT NULL
);

CREATE TABLE IF NOT EXISTS "Sanpham" (
    "Id" uuid PRIMARY KEY,
    "IdNhom" uuid NOT NULL REFERENCES "NhomSP"("Id") ON DELETE RESTRICT,
    "TenSP" varchar(100) NOT NULL,
    "MoTa" varchar(500),
    "GiaBan" numeric(10,2) NOT NULL,
    "GiaNhap" numeric(10,2) NOT NULL,
    "SoLuongTon" integer NOT NULL DEFAULT 0,
    "SLTonMin" integer NOT NULL DEFAULT 0,
    "DonViTinh" varchar(50),
    "IsActive" boolean NOT NULL DEFAULT true,
    "NgayTao" timestamp NOT NULL,
    "NgayCapNhat" timestamp NOT NULL
);

CREATE TABLE IF NOT EXISTS "Khachhang" (
    "Id" uuid PRIMARY KEY,
    "TenKH" varchar(100) NOT NULL,
